# Renders the API reference for the manual: xmldocmd (pinned in
# .config/dotnet-tools.json) reads the built Pain001.Sdk.dll and its XML
# documentation comments and writes one Markdown page per public type
# and member into docs/api/, which is generated and not committed.
# `make docs` and the docs workflow run it before `mkdocs build`.
set -euo pipefail

cd "$(dirname "$0")/.."
config="${CONFIG:-Release}"
dll="src/Pain001.Sdk/bin/$config/net10.0/Pain001.Sdk.dll"
[ -f "$dll" ] || dotnet build src/Pain001.Sdk/Pain001.Sdk.csproj -c "$config"

dotnet tool restore > /dev/null
rm -rf docs/api
dotnet xmldocmd "$dll" docs/api --visibility public --clean --quiet

# The assembly page is the reference's index.
mv docs/api/Pain001.Sdk.md docs/api/index.md
find docs/api -name '*.md' -exec sed -i.bak 's|Pain001\.Sdk\.md)|index.md)|g' {} +
find docs/api -name '*.bak' -delete
{
  echo
  echo "Generated by xmldocmd from the XML documentation comments of"
  echo "\`Pain001.Sdk.dll\`. xmldocmd lists an \`init\` accessor as \`set\`;"
  echo "the properties of \`RetryPolicy\` are \`init\`-only."
} >> docs/api/index.md
echo "api-docs: wrote $(find docs/api -name '*.md' | wc -l | tr -d ' ') pages to docs/api/"
